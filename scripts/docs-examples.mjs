import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import ts from 'typescript';
import { fileURLToPath } from 'node:url';

export function standaloneSource(source) {
  return source
    .replace(/\r\n/g, '\n')
    .replace(
      /import\s*\{\s*ExampleToaster as Toaster\s*\}\s*from ['"]\.\.\/app\/components\/example-toaster['"];\n?/,
      '',
    )
    .replace(
      "import { notia } from 'notia';",
      "import { notia, Toaster } from 'notia';",
    );
}
const directory = new URL('../apps/docs/examples/', import.meta.url);
const examples = Object.fromEntries(
  readdirSync(directory)
    .filter((file) => file.endsWith('.tsx'))
    .sort()
    .map((file) => {
      const source = standaloneSource(
        readFileSync(new URL(file, directory), 'utf8'),
      );
      const javascript = ts.transpileModule(source, {
        compilerOptions: {
          target: ts.ScriptTarget.ESNext,
          module: ts.ModuleKind.ESNext,
          jsx: ts.JsxEmit.Preserve,
        },
        reportDiagnostics: true,
      });
      if (javascript.diagnostics?.length)
        throw new Error(
          ts.formatDiagnosticsWithColorAndContext(javascript.diagnostics, {
            getCanonicalFileName: (file) => file,
            getCurrentDirectory: () => process.cwd(),
            getNewLine: () => '\n',
          }),
        );
      return [
        file.slice(0, -4),
        { typescript: source, javascript: javascript.outputText },
      ];
    }),
);
const output = `// Generated by scripts/docs-examples.mjs from the live examples.\nexport const exampleSources = ${JSON.stringify(examples, null, 2)} as const;\n`;
// Format deterministically so format checks and regeneration agree.
const prettier = await import('prettier');
const formatted = await prettier.format(output, {
  parser: 'typescript',
  ...(await prettier.resolveConfig(
    fileURLToPath(new URL('../package.json', import.meta.url)),
  )),
});
const destination = new URL(
  '../apps/docs/app/lib/example-sources.ts',
  import.meta.url,
);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8').replace(/\r\n/g, '\n') !== formatted)
    throw new Error(
      'Documentation examples changed. Run pnpm docs:examples to refresh copied code.',
    );
  console.log(
    `${Object.keys(examples).length} live documentation examples match their JavaScript and TypeScript code.`,
  );
} else writeFileSync(destination, formatted);
